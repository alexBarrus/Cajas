    private void btnVaciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVaciarActionPerformed
        if (pila.estaVacia()) {
            JOptionPane.showMessageDialog(this,
                    "El almacén ya está vacío.",
                    "Almacén vacío", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Seguro que quieres vaciar las " + pila.getTamanio() + " Cajas?",
                "Vaciar almacén", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (respuesta == JOptionPane.YES_OPTION) {
            pila.clear();
            dibujarTorre();
        }
    }//GEN-LAST:event_btnVaciarActionPerformed

    /** Dibuja la torre recorriendo los nodos desde la cima hasta el piso. */
    private void dibujarTorre() {
        StringBuilder sb = new StringBuilder();

        if (pila.estaVacia()) {
            sb.append("\n   (El almacén está vacío)\n\n");
        } else {
            int nivel = pila.getTamanio();
            Nodo actual = pila.getCima();
            while (actual != null) {
                Cajas c = actual.getCaja();
                String marca = (actual == pila.getCima()) ? "  <-- CIMA" : "";
                sb.append("   +----------------------------+\n");
                sb.append(String.format("   | #%-2d %-22s |%s%n", nivel, recortar(c.getCodigo(), 22), marca));
                sb.append(String.format("   | %-26s |%n", recortar(c.getContenido(), 26)));
                sb.append(String.format("   | %-26s |%n", String.format("%.2f kg", c.getPeso())));
                actual = actual.getSiguiente();
                nivel--;
            }
            sb.append("   +----------------------------+\n");
        }
        sb.append("  ================================  PISO\n");

        txtTorre.setText(sb.toString());
        txtTorre.setCaretPosition(0);
        lblTotal.setText(String.format("Cajas: %d   |   Peso total: %.2f kg",
                pila.getTamanio(), pila.pesoTotal()));
    }

    private String recortar(String texto, int max) {
        return texto.length() <= max ? texto : texto.substring(0, max - 1) + "…";
    }

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtContenido.setText("");
        txtPeso.setText("");
        txtCodigo.requestFocus();
    }

